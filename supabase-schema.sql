-- Boozy Bites mock storefront schema
-- Run this in Supabase SQL Editor when you are ready to persist waitlist signups.
create table if not exists public.waitlist (
  id bigint generated by default as identity primary key,
  email text not null unique,
  created_at timestamptz not null default now()
);

alter table public.waitlist enable row level security;

drop policy if exists "Anyone can join the waitlist"
  on public.waitlist;

drop policy if exists "Only authenticated users can view waitlist"
  on public.waitlist;

create policy "Anyone can join the waitlist"
  on public.waitlist for insert
  to anon
  with check (length(email) > 3 and position('@' in email) > 1);

create policy "Only authenticated users can view waitlist"
  on public.waitlist for select
  to authenticated
  using (true);

create table if not exists public.business_inquiries (
  id bigint generated by default as identity primary key,
  business_name text not null,
  contact_name text not null,
  email text not null,
  business_type text not null,
  message text,
  created_at timestamptz not null default now()
);

alter table public.business_inquiries enable row level security;

drop policy if exists "Anyone can submit a business inquiry"
  on public.business_inquiries;

drop policy if exists "Only authenticated users can view business inquiries"
  on public.business_inquiries;

create policy "Anyone can submit a business inquiry"
  on public.business_inquiries for insert
  to anon
  with check (
    length(business_name) > 1
    and length(contact_name) > 1
    and length(email) > 3
    and position('@' in email) > 1
  );

create policy "Only authenticated users can view business inquiries"
  on public.business_inquiries for select
  to authenticated
  using (true);

